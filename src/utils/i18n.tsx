export function formatRelativeDayLocalized(dateStr: string | undefined, lang: LanguageId): string {
  if (!dateStr) return '';
  let parsed: Date;
  try {
    parsed = parseISO(dateStr);
  } catch {
    return dateStr;
  }
  if (Number.isNaN(parsed.getTime())) return dateStr;
  const diff = differenceInCalendarDays(parsed, new Date());

  if (lang === 'ar') {
    if (diff === 0) return 'اليوم';
    if (diff === 1) return 'غداً';
    if (diff === -1) return 'أمس';
    if (diff < 0) return `منذ ${Math.abs(diff)} يوم`;
    if (diff < 7) return `بعد ${diff} أيام`;
    return `بعد ${Math.round(diff / 7)} أسابيع`;
  }
  if (lang === 'arz') {
    if (diff === 0) return 'النهاردة';
    if (diff === 1) return 'بكرة';
    if (diff === -1) return 'امبارح';
    if (diff < 0) return `من ${Math.abs(diff)} يوم`;
    if (diff < 7) return `بعد ${diff} أيام`;
    return `بعد ${Math.round(diff / 7)} أسابيع`;
  }
  if (lang === 'fr') {
    if (diff === 0) return "Aujourd'hui";
    if (diff === 1) return 'Demain';
    if (diff === -1) return 'Hier';
    if (diff < 0) return `Il y a ${Math.abs(diff)} j`;
    if (diff < 7) return `Dans ${diff} j`;
    return `Dans ${Math.round(diff / 7)} sem.`;
  }
  if (lang === 'genz') {
    if (diff === 0) return 'Today rn';
    if (diff === 1) return 'Tmrw';
    if (diff === -1) return 'Yesterday';
    if (diff < 0) return `${Math.abs(diff)}d ago`;
    if (diff < 7) return `In ${diff}d`;
    return `In ${Math.round(diff / 7)}w`;
  }
  if (diff === 0) return 'Today';
  if (diff === 1) return 'Tomorrow';
  if (diff === -1) return 'Yesterday';
  if (diff < 0) return `${Math.abs(diff)} days ago`;
  if (diff < 7) return `In ${diff} days`;
  if (diff < 14) return `In ${Math.round(diff / 7)} week`;
  return `In ${Math.round(diff / 7)} weeks`;
}

export function formatLocalizedDate(
  dateInput: Date | string | undefined,
  pattern: string,
  lang: LanguageId
): string {
  if (!dateInput) return '';
  try {
    const parsed = typeof dateInput === 'string' ? parseISO(dateInput) : dateInput;
    if (Number.isNaN(parsed.getTime())) return typeof dateInput === 'string' ? dateInput : '';
    return format(parsed, pattern, { locale: getDateLocale(lang) });
  } catch {
    return typeof dateInput === 'string' ? dateInput : '';
  }
}

interface LanguageContextValue {
  lang: LanguageId;
  setLang: (next: LanguageId) => void;
  isRtl: boolean;
  t: (key: TranslationKeys) => string;
}

const LanguageContext = createContext<LanguageContextValue>({
  lang: 'en',
  setLang: () => {},
  isRtl: false,
  t: (key) => TRANSLATIONS.en[key],
});

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<LanguageId>(() => getSavedLanguageId());

  useEffect(() => {
    applyLanguage(lang);
  }, [lang]);

  const setLang = useCallback((next: LanguageId) => {
    setLangState(next);
    applyLanguage(next);
  }, []);

  const isRtl = lang === 'ar' || lang === 'arz';

  const t = useCallback(
    (key: TranslationKeys): string => {
      return TRANSLATIONS[lang]?.[key] || TRANSLATIONS.en[key];
    },
    [lang]
  );

  const value = useMemo(() => ({ lang, setLang, isRtl, t }), [lang, setLang, isRtl, t]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useTranslation() {
  return useContext(LanguageContext);
}
