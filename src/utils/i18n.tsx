export interface LanguageOption {
  id: LanguageId;
  name: string;
  nativeName: string;
  shortLabel: string;
  dir: 'ltr' | 'rtl';
}

export const LANGUAGES: LanguageOption[] = [
  { id: 'en', name: 'English', nativeName: 'English', shortLabel: 'EN', dir: 'ltr' },
  { id: 'ar', name: 'Arabic', nativeName: 'العربية', shortLabel: 'AR', dir: 'rtl' },
  { id: 'genz', name: 'Gen Z / Alpha', nativeName: 'Gen Z / Alpha', shortLabel: 'GZ', dir: 'ltr' },
  { id: 'fr', name: 'French', nativeName: 'Français', shortLabel: 'FR', dir: 'ltr' },
  { id: 'arz', name: 'Egyptian Arabic', nativeName: 'مصري', shortLabel: 'EG', dir: 'rtl' },
];

const LANGUAGE_KEY = 'examiner_language_id';

export function isValidLanguageId(val: unknown): val is LanguageId {
  return val === 'en' || val === 'ar' || val === 'genz' || val === 'fr' || val === 'arz';
}

export function getSavedLanguageId(): LanguageId {
  try {
    const raw = localStorage.getItem(LANGUAGE_KEY);
    if (isValidLanguageId(raw)) return raw;
  } catch {
    // Ignore
  }
  return 'en';
}

export function applyLanguage(lang: LanguageId): void {
  try {
    localStorage.setItem(LANGUAGE_KEY, lang);
  } catch {
    // Ignore
  }
  if (typeof document !== 'undefined') {
    const meta = LANGUAGES.find((l) => l.id === lang) || LANGUAGES[0];
    document.documentElement.lang = lang === 'arz' ? 'ar-EG' : lang === 'genz' ? 'en' : lang;
    document.documentElement.dir = meta.dir;
  }
}

export function getDateLocale(lang: LanguageId) {
  if (lang === 'ar' || lang === 'arz') return ar;
  if (lang === 'fr') return fr;
  return enUS;
}

